-- EditFlow initial schema.
-- Enums are VARCHAR + CHECK (mapped with @Enumerated(STRING)) so adding a value is a one-line migration.
-- Derived values (progress, revision count, total paid, balance) are deliberately NOT stored.

CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(120) NOT NULL,
    email                VARCHAR(254) NOT NULL,
    password_hash        VARCHAR(100) NOT NULL,
    role                 VARCHAR(20)  NOT NULL,
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at           TIMESTAMPTZ  NOT NULL,
    updated_at           TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'CLIENT'))
);

CREATE TABLE clients (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(120) NOT NULL,
    email        VARCHAR(254) NOT NULL,
    phone        VARCHAR(30),
    instagram    VARCHAR(60),
    company_name VARCHAR(120),
    notes        TEXT,
    user_id      BIGINT,
    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uk_clients_email UNIQUE (email),
    CONSTRAINT uk_clients_user UNIQUE (user_id),
    CONSTRAINT ck_clients_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT fk_clients_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE TABLE projects (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    BIGINT        NOT NULL,
    name         VARCHAR(150)  NOT NULL,
    description  TEXT,
    period_month INTEGER       NOT NULL,
    period_year  INTEGER       NOT NULL,
    total_fee    NUMERIC(12, 2) NOT NULL,
    status       VARCHAR(20)   NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL,
    updated_at   TIMESTAMPTZ   NOT NULL,
    CONSTRAINT fk_projects_client FOREIGN KEY (client_id) REFERENCES clients (id),
    -- One project per client per month: prevents duplicates from double-accepting an inquiry.
    CONSTRAINT uk_projects_client_period UNIQUE (client_id, period_month, period_year),
    CONSTRAINT ck_projects_month CHECK (period_month BETWEEN 1 AND 12),
    CONSTRAINT ck_projects_year CHECK (period_year BETWEEN 2000 AND 2100),
    CONSTRAINT ck_projects_fee CHECK (total_fee >= 0),
    CONSTRAINT ck_projects_status CHECK (status IN ('ACTIVE', 'COMPLETED', 'ARCHIVED'))
);
CREATE INDEX idx_projects_status ON projects (status);

CREATE TABLE inquiries (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(120)   NOT NULL,
    email              VARCHAR(254)   NOT NULL,
    phone_or_instagram VARCHAR(100)   NOT NULL,
    content_type       VARCHAR(120)   NOT NULL,
    videos_per_month   INTEGER        NOT NULL,
    budget             NUMERIC(12, 2) NOT NULL,
    deadline           DATE,
    description        TEXT,
    status             VARCHAR(20)    NOT NULL,
    client_id          BIGINT,
    project_id         BIGINT,
    version            BIGINT         NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ    NOT NULL,
    updated_at         TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_inquiries_client FOREIGN KEY (client_id) REFERENCES clients (id),
    CONSTRAINT fk_inquiries_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_inquiries_videos CHECK (videos_per_month > 0),
    CONSTRAINT ck_inquiries_budget CHECK (budget >= 0),
    CONSTRAINT ck_inquiries_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT ck_inquiries_accepted_links CHECK (
        status <> 'ACCEPTED' OR (client_id IS NOT NULL AND project_id IS NOT NULL))
);
CREATE INDEX idx_inquiries_status ON inquiries (status);

CREATE TABLE videos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id        BIGINT        NOT NULL,
    title             VARCHAR(200)  NOT NULL,
    content_type      VARCHAR(20)   NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    deadline          DATE,
    drive_url         VARCHAR(2048),
    media_received_at TIMESTAMPTZ,
    edit_completed_at TIMESTAMPTZ,
    delivered_at      TIMESTAMPTZ,
    created_at        TIMESTAMPTZ   NOT NULL,
    updated_at        TIMESTAMPTZ   NOT NULL,
    CONSTRAINT fk_videos_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT ck_videos_content_type CHECK (content_type IN ('REEL', 'YOUTUBE_SHORT', 'YOUTUBE_VIDEO', 'PODCAST')),
    CONSTRAINT ck_videos_status CHECK (status IN ('PENDING', 'MEDIA_RECEIVED', 'EDITING', 'REVIEW', 'COMPLETED', 'DELIVERED')),
    CONSTRAINT ck_videos_drive_url CHECK (drive_url IS NULL OR drive_url ~* '^https?://')
);
CREATE INDEX idx_videos_project ON videos (project_id);
CREATE INDEX idx_videos_status ON videos (status);
CREATE INDEX idx_videos_deadline ON videos (deadline);

CREATE TABLE revisions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id     BIGINT      NOT NULL,
    timecode     VARCHAR(8)  NOT NULL,
    comment      TEXT        NOT NULL,
    status       VARCHAR(20) NOT NULL,
    requested_by VARCHAR(20) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL,
    resolved_at  TIMESTAMPTZ,
    CONSTRAINT fk_revisions_video FOREIGN KEY (video_id) REFERENCES videos (id) ON DELETE CASCADE,
    CONSTRAINT ck_revisions_timecode CHECK (timecode ~ '^([0-9]{1,2}:)?[0-5][0-9]:[0-5][0-9]$'),
    CONSTRAINT ck_revisions_status CHECK (status IN ('OPEN', 'RESOLVED')),
    CONSTRAINT ck_revisions_requested_by CHECK (requested_by IN ('ADMIN', 'CLIENT')),
    CONSTRAINT ck_revisions_resolved_at CHECK ((status = 'RESOLVED') = (resolved_at IS NOT NULL))
);
CREATE INDEX idx_revisions_video_status ON revisions (video_id, status);

CREATE TABLE payments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id   BIGINT         NOT NULL,
    amount       NUMERIC(12, 2) NOT NULL,
    payment_date DATE           NOT NULL,
    note         VARCHAR(255),
    created_at   TIMESTAMPTZ    NOT NULL,
    CONSTRAINT fk_payments_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_payments_amount CHECK (amount > 0)
);
CREATE INDEX idx_payments_project ON payments (project_id);
